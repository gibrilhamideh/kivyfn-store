from enum import Enum


class Policy(str, Enum):
    CASCADE = "CASCADE"
    RESTRICT = "RESTRICT"


class ConstraintType(str, Enum):
    UNIQUE = "unique"
    FK_MISSING = "fk_missing"
    FK_RESTRICT = "fk_restrict"


class InstructionOpCode(str, Enum):
    SET = "set"
    SETROW = "setrow"
    INSERT = "insert"
    REMOVE = "remove"

    def __str__(self) -> str:
        return self.value


class InstructionSource(str, Enum):
    COMMAND = "command"  # direct user/store request
    TRIGGER = "trigger"  # generated by trigger logic
    POLICY = "policy"  # generated by FK cascade / engine policy

    def __str__(self) -> str:
        return self.value
